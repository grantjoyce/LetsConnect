/** Flattened [{ ref, levelSlug, text, sortOrder }] in catalogue order. */
function allQuestions() {
  const out = [];
  for (const level of LEVELS) {
    const rows = QUESTIONS[level.slug] || [];
    rows.forEach(([ref, text], i) => {
      out.push({ ref, levelSlug: level.slug, text, sortOrder: i + 1 });
    });
  }
  return out;
}

